def source_modules (base_dir) :

   # -- hlavni adresar: podadresare, testy, vystup --

   d = Module ("", "")
   d.subdir ("asm")
   d.subdir ("cmini")

   d.rule ("test", "", "sh tests/build-test.sh", phony = True)
   d.rule ("test-lexer", "", "LEXER=lexer sh tests/build-test.sh", phony = True)
   d.rule ("test-translate", "", "sh tests/build-translate.sh", phony = True)
   # bootstrap c-mini bez gcc: TinyCC (TCC=/opt/tinycc/bin/tcc), chibicc - samopreklad, pevny bod
   d.rule ("test-tcc", "", "sh tests/build-tcc.sh", phony = True)
   # pasm: 16/32 bitu proti verzi v Pascalu (fpc), x86-64 a kodovani instrukci proti nasm
   d.rule ("test-asm", "", "$(MAKE) -C asm test test-nasm test-nasm64 test-toaru", phony = True)
   # _output/ - vznikle soubory pro studenty (C, .asm, ... z tests/examples/*.cc)
   d.rule ("vystup", "all", "sh tests/output.sh", phony = True)
   # bezna sada (~1-2 min, README kap. 0): cmini (generator, C99, translate, TinyCC), pasm
   d.rule ("test-quick", "all", "$(MAKE) test test-asm test-translate test-tcc", phony = True)
   # kompletni sada (pred zalohou, po zmene spolecnych casti): test-quick a vse ostatni
   d.rule ("test-all", "all", "$(MAKE) test-quick",
           "$(MAKE) test-lexer",
           "VYSTUP_TOARU=0 sh tests/output.sh", phony = True)
   # ToaruOS v QEMU (test 04 a check.sh) - jen po zmene cmini, asm nebo toaruos-tools
   d.rule ("test-toaru-all", "all", "sh tests/04-toaru.sh", "toaruos-tools/check.sh", phony = True)

   d.clean_dir ("$(top_srcdir)/_build", "$(top_srcdir)/_output")  # vystupy testu, tests/output.sh

   # -- asm: assembler pasm a knihovna libpasm.a (drive rucne psany asm/makefile) --

   d = Module ("ASM", "asm")
   d.c_flags ("-O1", "-std=c99", "-pedantic", "-Wall", "-Wextra")   # assembler je v cistem C (TinyCC)

   # knihovna: pasmlib.h (PasmAssemble, PasmAssembleText) a asmlist.h (program jako
   # spojovy seznam, ciste C) - pouziva cmini (instr.c)
   d.library ("libpasm.a")
   d.prog_source ("pasmlib.c", "code.c", "def.c", "expr.c", "inst.c", "key.c", "oth.c", "asmlist.c")

   d.program ("pasm.bin")
   d.prog_source ("pasm.c")
   d.prog_lib ("libpasm.a")

   # tests/asmlist_test.c => stejny ELF jako pasm -e tests/hello64.asm (faze 2 - uzly primo, i faze 1 - pres text)
   d.rule ("test-asmlist", "libpasm.a pasm.bin",
           "$(CC) $(CFLAGS) -I . tests/asmlist_test.c libpasm.a -o tests/_asmlist_test",
           "cd tests && ./_asmlist_test > _asmlist.asm && ../pasm.bin -e -l hello64.asm > /dev/null && \\",
           "   cmp hello64.bin hello64_list.bin && cmp hello64.bin hello64_text.bin && \\",
           "   cmp hello64_list.lst hello64_text.lst && chmod +x hello64_list.bin && \\",
           "   { ./hello64_list.bin > /dev/null; test $$? = 35; } && echo \"asmlist: OK (stejny ELF, faze 1 = faze 2, exit 35)\"",
           "rm -f tests/_asmlist_test tests/_asmlist.asm tests/hello64.bin tests/hello64.lst \\",
           "      tests/hello64_list.bin tests/hello64_list.lst tests/hello64_text.bin tests/hello64_text.lst",
           phony = True)
   # 16/32 bitu proti verzi v Pascalu (../../pascal-text/asm, fpc), x86-64 proti nasm; vystupy v _build/asm
   d.rule ("test", "pasm.bin", "ASM_OUTPUT=$(BUILD)/tests sh tests/run.sh $(CURDIR)/pasm.bin", phony = True)
   d.rule ("test-nasm", "pasm.bin", "python3 -I tests/nasmcmp.py $(CURDIR)/pasm.bin $(BUILD)/nasmcmp", phony = True)
   d.rule ("test-nasm64", "pasm.bin", "python3 -I tests/nasm64cmp.py $(CURDIR)/pasm.bin $(abspath $(BUILD))/nasm64cmp", phony = True)
   # terc ToaruOS (-T): TENTYZ ELF64 writer jen od adresy 0x3F000000 (0x400000
   # v hostovi dostane SIGSEV jeste pred prvnim syscallem). Srovnani s referencnim
   # obrazem (probe/toaru64.bin) odstraneno - overuje se adresa LOAD a navrat pasm.
   # Bez -T musi zustat zakladna Linuxu, tj. linuxova cesta se nesmi hnout.
   d.rule ("test-toaru", "pasm.bin",
           "mkdir -p $(BUILD)/toaru",
           "cp $(top_srcdir)/toaruos-tools/probe/toaru64.asm $(top_srcdir)/asm/tests/hello32.asm $(BUILD)/toaru/",
           "cd $(BUILD)/toaru && $(CURDIR)/pasm.bin -e -T toaru64.asm",
           "test \"$$(readelf -W -l $(BUILD)/toaru/toaru64.bin | awk '/[[:space:]]LOAD[[:space:]]/{print $$3; exit}')\" \\",
           "      = 0x000000003f000000 && echo \"toaru: OK (-T => obraz od 0x3F000000)\"",
           "cd $(BUILD)/toaru && $(CURDIR)/pasm.bin -e toaru64.asm",
           "test \"$$(readelf -W -l $(BUILD)/toaru/toaru64.bin | awk '/[[:space:]]LOAD[[:space:]]/{print $$3; exit}')\" \\",
           "      = 0x0000000000400000 && echo \"toaru: OK (bez -T zakladna 0x400000, linuxova cesta beze zmeny)\"",
           # -T ma vyznam jen k -e (OMF ani ET_REL zakladnu nemaji) a vyzaduje USE64
           "{ cd $(BUILD)/toaru && $(CURDIR)/pasm.bin -T toaru64.asm > /dev/null 2>&1; test $$? = 2; } \\",
           "   && echo \"toaru: OK (-T bez -e => napoveda, navrat 2)\"",
           "{ cd $(BUILD)/toaru && $(CURDIR)/pasm.bin -e -T hello32.asm > /dev/null 2>&1; test $$? -ne 0; } \\",
           "   && echo \"toaru: OK (-T + USE32 => chyba: ToaruOS target requires USE64 segments)\"",
           # data pred kodem: jadro odmita ukazatele pod e_entry => skok JMP start
           # hned za hlavickou (e_entry 0x3F000078, bajt E9), overeno v hostovi
           "cp $(top_srcdir)/toaruos-tools/probe/openpos.asm $(BUILD)/toaru/",
           "cd $(BUILD)/toaru && $(CURDIR)/pasm.bin -e -T openpos.asm",
           "test \"$$(readelf -h $(BUILD)/toaru/openpos.bin | awk '/Entry point/{print $$NF}') $$(od -An -tx1 -j 120 -N 1 $(BUILD)/toaru/openpos.bin)\" \\",
           "      = \"0x3f000078  e9\" && echo \"toaru: OK (data pred kodem => e_entry = JMP start za hlavickou)\"",
           phony = True)

   # -- cmini: prekladac c-mini (cparser) - programy v cmini/ --

   d = Module ("CMINI", "cmini")
   d.cflags ("-g", "-std=c++20", "-fpermissive", "-w")
   d.c_flags ("-g", "-std=gnu11", "-w", "-fno-asynchronous-unwind-tables")
   # front-end a translate.c - ciste C (TinyCC): bez .eh_frame jako TinyCC - chyby
   # nesmi prochazet ramci C jako vyjimky C++ (showError v test_instr.cc: longjmp)
   d.ext_library ("$(top_srcdir)/asm/libpasm.a", "$(top_srcdir)/asm", "libpasm.a")

