#!/usr/bin/env python3

# cmini-makefiles.py - generuje Makefile pro projekt cecko
#                      (styl /abc/gibbon/makefiles.py, bez make.conf, cmake a qmake)
#
#   python3 cmini-makefiles.py            Makefile (hlavni adresar) a asm/, cmini/
#   python3 cmini-makefiles.py --print    jen vypis na standardni vystup
#   python3 cmini-makefiles.py --force    prepsat i Makefile, ktery negeneroval tento skript
#
# Kazdy podadresar preklada sve programy a knihovny (asm/pasm.bin, asm/libpasm.a,
# cmini/test_instr.bin, ..., cmini/cmini.bin), objekty jsou v _build/<adresar>.
# Hlavni Makefile vola podadresare a spousti testy.
#
# Konvence: generovany soubor je Makefile (velke M), rucne psany makefile
# (male m, napr. gccplugin/makefile) - negeneruje se, jen se vola (make -C ...).
# GNU make dava makefile prednost pred Makefile, proto se do adresare
# s rucne psanym makefile Makefile negeneruje.
# Vygenerovany Makefile zacina radkou GENERATED_MARK; cmini-files.py ho
# podle ni vynecha ze zalohy.

import sys, os, optparse

GENERATED_MARK = "# Makefile is generated by cmini-makefiles.py"
OLD_GENERATED_MARKS = ("# Makefile is generated by cecko-makefiles.py",)   # Makefile z driv

opt = None
module_list = [ ]

# --------------------------------------------------------------------------

class ProgramInfo (object) :
   def __init__ (self, name) :
       self.name = name           # jmeno spustitelneho souboru
       self.sources = [ ]         # zdrojove soubory (relativne k adresari modulu)
       self.cflags = [ ]          # navic k CXXFLAGS modulu
       self.ldflags = [ ]
       self.libs = [ ]            # knihovny (soubory) - zavislosti programu
       self.in_all = True         # soucast cile all
       self.cond_items = [ ]      # (podminka, druh, hodnota): druh source, cflags, ldflags
       self.order_deps = [ ]      # pred prekladem objektu (vygenerovane hlavicky)
       self.source_cflags = { }   # zdroj => volby jen pro tento soubor (za CXXFLAGS programu)
       self.is_library = False    # staticka knihovna (ar), napr. asm/libpasm.a

class ModuleInfo (object) :
   def __init__ (self, p_name, p_directory) :
       self.m_name = p_name
       self.m_directory = p_directory
       self.cxx = "g++"
       self.cxxflags = [ ]
       self.cc = "gcc"            # zdroje .c (napr. asm/asmlist.c)
       self.ccflags = [ ]
       self.programs = [ ]
       self.subdirs = [ ]         # adresare s vlastnim Makefile (make -C)
       self.ext_libs = [ ]        # (knihovna, adresar, cil) - preklad v jinem adresari
       self.ext_progs = [ ]       # (program, adresar, cil)
       self.variables = [ ]       # (jmeno, hodnota)
       self.rules = [ ]           # dalsi pravidla (text)
       self.phony = [ ]
       self.clean_files = [ ]
       self.clean_dirs = [ ]
       self.configs = [ ]         # (jmeno, implicitni hodnota) - make NAME= ... zmeni
       self.build = ""            # podadresar v $(top_srcdir)/_build (objekty, vystupy)
       self.current_cond = ""     # d.cond (...) jako v makefiles.py
       self.text = ""
       module_list.append (self)

   # nastaveni modulu

   def cflags (self, * args) :
       self.cxxflags.extend (args)

   def c_flags (self, * args) :
       # CFLAGS pro zdroje .c (CXXFLAGS programu se na ne nepouziji)
       self.ccflags.extend (args)

   def subdir (self, name) :
       self.subdirs.append (name)

   def ext_library (self, lib, directory, target) :
       self.ext_libs.append ((lib, directory, target))

   def ext_program (self, prog, directory, target) :
       self.ext_progs.append ((prog, directory, target))

   def assign (self, name, value) :
       self.variables.append ((name, value))

   def config (self, name, value, immediate = False) :
       # volba prekladu, napr. USE_ASM_JIT = 1 (make USE_ASM_JIT= ... vypne)
       # immediate: hodnota se vyhodnoti hned (:=), napr. $(shell ...) - ifdef
       #    hodnotu nerozvine, USE_X ?= $(shell ...) by bylo vzdy definovane
       # zmena voleb (make USE_X= ...) prelozi objekty znovu (soubor $(BUILD)/.config)
       self.configs.append ((name, value, immediate))

   def cond (self, cond) :
       # nasledujici prog_source, prog_cflags, prog_ldflags jen pri ifdef cond ("" = vzdy)
       self.current_cond = cond

   # programy

   def program (self, name) :
       p = ProgramInfo (name)
       self.programs.append (p)
       self.last_program = p
       return p

   def library (self, name) :
       # staticka knihovna (ar rcs), zdroje a volby jako u programu
       p = self.program (name)
       p.is_library = True
       return p

   def prog_item (self, kind, args) :
       p = self.last_program
       for a in args :
           if self.current_cond == "" :
              { "source" : p.sources, "cflags" : p.cflags, "ldflags" : p.ldflags } [kind].append (a)
           else :
              p.cond_items.append ((self.current_cond, kind, a))

   def prog_source (self, * args) :
       self.prog_item ("source", args)

   def prog_cflags (self, * args) :
       self.prog_item ("cflags", args)

   def prog_ldflags (self, * args) :
       self.prog_item ("ldflags", args)

   def prog_source_cflags (self, src, * args) :
       # volby jen pro jeden zdroj, napr. -std=c++20 pro hlavicky asmjit 1.25
       self.last_program.source_cflags.setdefault (src, [ ]).extend (args)

   def prog_order (self, * args) :
       # objekty programu az po jinem cili (napr. vygenerovany parser v jinem adresari)
       self.last_program.order_deps.extend (args)

   def prog_moc (self, * headers) :
       # Qt: moc z hlavicky s Q_OBJECT => $(BUILD)/moc/x_moc.cpp, prelozi se jako dalsi zdroj
       # programu; MOC a MOC_FLAGS (stejne -D jako pri prekladu - #ifdef v hlavickach) v modulu
       for h in headers :
           base = os.path.splitext (os.path.basename (h)) [0]
           cpp = "$(BUILD)/moc/" + base + "_moc.cpp"
           self.rule (cpp, h, "@mkdir -p $(@D)", "$(MOC) $(MOC_FLAGS) $< -o $@")
           self.prog_source (cpp)

   def prog_lib (self, * args) :
       self.last_program.libs.extend (args)

   def prog_not_in_all (self) :
       self.last_program.in_all = False

   # dalsi pravidla

   def rule (self, target, deps, * commands, phony = False) :
       txt = target + ":"
       if deps :
          txt = txt + " " + deps
       txt = txt + "\n"
       for c in commands :
           txt = txt + "\t" + c + "\n"
       self.rules.append (txt)
       if phony :
          self.phony.append (target)

   def clean (self, * args) :
       self.clean_files.extend (args)

   def clean_dir (self, * args) :
       self.clean_dirs.extend (args)

def Module (p_name, p_directory) :
    return ModuleInfo (p_name, p_directory)

# --------------------------------------------------------------------------

def obj_name (prog, src) :
    base = os.path.splitext (os.path.basename (src)) [0]
    return "$(BUILD)/" + prog_id (prog) + "/" + base + ".o"

def prog_id (prog) :
    return os.path.splitext (prog.name) [0]

def var_list (name, values) :
    if len (values) == 0 :
       return name + " =\n\n"
    return name + " = \\\n" + " \\\n".join ("   " + v for v in values) + "\n\n"

def all_sources (p) :
    return p.sources + [ v for c, k, v in p.cond_items if k == "source" ]

def check_programs (d) :
    for p in d.programs :
        names = { }
        for src in all_sources (p) :
            o = obj_name (p, src)
            if o in names :
               print ("ERROR: " + d.m_directory + ": " + p.name + ": " + src + " and " + names [o] + " -> " + o)
               sys.exit (1)
            names [o] = src

def prepare_makefile (d) :
    check_programs (d)

    t = GENERATED_MARK + "\n\n"

    depth = 0 if d.m_directory == "" else len (d.m_directory.split ("/"))
    top = "." if depth == 0 else "/".join ([".."] * depth)
    t = t + "top_srcdir = " + top + "\n"
    # objekty a vystupy vsech modulu v jednom adresari _build (hlavni adresar)
    if d.m_directory != "" :
       t = t + "BUILD = $(top_srcdir)/_build/" + (d.build if d.build != "" else d.m_directory) + "\n"
    t = t + "\n"

    for name, value, immediate in d.configs :
        if immediate :
           t = t + "ifeq ($(origin " + name + "),undefined)\n"
           t = t + "   " + name + " := " + value + "\n"
           t = t + "endif\n"
        else :
           t = t + name + " ?= " + value + "\n"
    if d.configs :
       t = t + "\n"

    if any (not src.endswith (".c") for p in d.programs for src in all_sources (p)) :
       t = t + "CXX = " + d.cxx + "\n"
       t = t + var_list ("CXXFLAGS", d.cxxflags)
    if any (src.endswith (".c") for p in d.programs for src in all_sources (p)) :
       t = t + "CC = " + d.cc + "\n"
       t = t + var_list ("CFLAGS", d.ccflags)

    for name, value in d.variables :
        t = t + name + " = " + value + "\n"
    if d.variables :
       t = t + "\n"

    # all

    all_list = [ p.name for p in d.programs if p.in_all ]
    if d.subdirs :
       all_list = [ "subdirs" ] + all_list
    t = t + "all: " + " ".join (all_list) + "\n\n"

    phony = [ "all", "clean" ]

    if d.subdirs :
       t = t + "subdirs:\n"
       for s in d.subdirs :
           t = t + "\t$(MAKE) -C " + s + "\n"
       t = t + "\n"
       phony.append ("subdirs")

    # knihovny a programy z jinych adresaru - preklad vlastnim Makefile,
    # FORCE: make se zepta podrizeneho Makefile (soubor se zmeni jen je-li potreba)

    force = False
    for lib, directory, target in d.ext_libs + d.ext_progs :
        t = t + lib + ": FORCE\n"
        t = t + "\t$(MAKE) -C " + directory + " " + target + "\n\n"
        force = True
    # volby prekladu: soubor $(BUILD)/.config se prepise jen pri zmene hodnot,
    # objekty na nem zavisi (zmena volby prelozi znovu jen zavisle objekty)
    if d.configs :
       text = " ".join (name + "=$(" + name + ")" for name, value, immediate in d.configs)
       t = t + "CONFIG_STAMP = $(BUILD)/.config\n"
       t = t + "CONFIG_TEXT = " + text + "\n\n"
       t = t + "$(CONFIG_STAMP): FORCE\n"
       t = t + "\t@mkdir -p $(@D)\n"
       t = t + "\t@echo '$(CONFIG_TEXT)' | cmp -s - $@ || echo '$(CONFIG_TEXT)' > $@\n\n"
       force = True

    if force :
       t = t + "FORCE:\n\n"
       phony.append ("FORCE")

    # programy

    for p in d.programs :
        id = prog_id (p).replace ("-", "_")
        objs = [ obj_name (p, src) for src in p.sources ]
        t = t + var_list (id + "_OBJECTS", objs)
        # volby programu (prog_cflags, napr. -DUSE_LEXER) - pro zdroje .cc i .c
        t = t + var_list (id + "_FLAGS", p.cflags)
        t = t + var_list (id + "_LDFLAGS", p.ldflags)
        conds = [ ]
        for c, k, v in p.cond_items :
            if c not in conds :
               conds.append (c)
        for c in conds :
            t = t + "ifdef " + c + "\n"
            for c2, k, v in p.cond_items :
                if c2 == c :
                   if k == "source" :
                      t = t + "   " + id + "_OBJECTS += " + obj_name (p, v) + "\n"
                   elif k == "cflags" :
                      t = t + "   " + id + "_FLAGS += " + v + "\n"
                   else :
                      t = t + "   " + id + "_LDFLAGS += " + v + "\n"
            t = t + "endif\n\n"
        t = t + p.name + ": $(" + id + "_OBJECTS)" + "".join (" " + lib for lib in p.libs) + "\n"
        if p.is_library :
           t = t + "\trm -f $@\n"
           t = t + "\tar rcs $@ $(" + id + "_OBJECTS)\n\n"
        else :
           # jen zdroje .c => linkuje $(CC) (program v cistem C, napr. asm/pasm.bin)
           if all (src.endswith (".c") for src in all_sources (p)) :
              t = t + "\t$(CC) $(CFLAGS)"
           else :
              t = t + "\t$(CXX) $(CXXFLAGS)"
           t = t + " $(" + id + "_OBJECTS)" + "".join (" " + lib for lib in p.libs)
           t = t + " $(" + id + "_LDFLAGS) -o $@\n\n"
        if p.order_deps :
           t = t + "$(" + id + "_OBJECTS): | " + " ".join (p.order_deps) + "\n\n"
        if d.configs :
           t = t + "$(" + id + "_OBJECTS): $(CONFIG_STAMP)\n\n"
        for src in all_sources (p) :
            o = obj_name (p, src)
            t = t + o + ": " + src + "\n"
            t = t + "\t@mkdir -p $(@D)\n"
            extra = "".join (" " + f for f in p.source_cflags.get (src, [ ]))
            if src.endswith (".c") :
               t = t + "\t$(CC) $(CFLAGS) $(" + id + "_FLAGS)" + extra + " -MMD -MP -c $< -o $@\n\n"
            else :
               t = t + "\t$(CXX) $(CXXFLAGS) $(" + id + "_FLAGS)" + extra + " -MMD -MP -c $< -o $@\n\n"
        t = t + "-include $(" + id + "_OBJECTS:.o=.d)\n\n"

    # dalsi pravidla

    for r in d.rules :
        t = t + r + "\n"
    phony = phony + d.phony

    # clean

    t = t + "# CLEAN\n\n"
    files = [ p.name for p in d.programs ] + d.clean_files
    dirs = [ ]
    if d.programs or d.build != "" :
       dirs.append ("$(BUILD)")
    dirs = dirs + d.clean_dirs
    t = t + var_list ("CLEAN_FILES", files)
    t = t + "clean:\n"
    if dirs :
       t = t + "\t- rm -rf " + " ".join (dirs) + "\n"
    t = t + "\ttest -z \"$(CLEAN_FILES)\" || rm -f $(CLEAN_FILES)\n"
    for s in d.subdirs :
        t = t + "\t$(MAKE) -C " + s + " clean\n"
    t = t + "\n"

    t = t + ".PHONY: " + " ".join (phony) + "\n"

    d.text = t

# --------------------------------------------------------------------------

def print_makefiles (base_dir) :
    for d in module_list :
        prepare_makefile (d)
        file_name = os.path.join (base_dir, d.m_directory, "Makefile")
        rel_name = os.path.join (d.m_directory, "Makefile")

        if os.path.isfile (os.path.join (base_dir, d.m_directory, "makefile")) :
           print ("SKIP  " + rel_name + " (v adresari je rucne psany makefile)")
           continue

        if opt.print_only :
           print ("# ---- " + rel_name + " ----")
           print (d.text)
           continue

        if os.path.isfile (file_name) and not opt.force :
           f = open (file_name, "r")
           first = f.readline ().rstrip ("\n")
           f.close ()
           if first != GENERATED_MARK and first not in OLD_GENERATED_MARKS :
              print ("SKIP  " + rel_name + " (neni generovany, prepsat: --force)")
              continue

        print ("Makefile for " + (d.m_name or "top") + " (" + rel_name + ")")
        f = open (file_name, "w")
        f.write (d.text)
        f.close ()

