#!/usr/bin/env python3

# cmini-files.py - seznam souboru projektu cecko pro zalohovani
#                  (styl /abc/gibbon/files.py)
#
#   python3 cmini-files.py                 soubory pro zalohu (relativne k adresari skriptu)
#   python3 cmini-files.py -c              skript pro uklid (rm ... vygenerovanych souboru)
#   python3 cmini-files.py -t | -p N | -f RRRR-MM-DD
#                                          jen soubory zmenene dnes / za N dni / od data
#   python3 cmini-files.py --one-dir-name  jmena s prefixem cecko/
#   python3 cmini-files.py --no-orig       bez adresare orig/
#
# Na rozdil od files.py:
#   - Makefile se vynecha, jen kdyz ho vygeneroval cmini-makefiles.py;
#     rucne psane se jmenuji makefile (male m, napr. tiny-ide/makefile) a zalohuji se,
#   - .cpp, .hpp, .tpp se zalohuji,
#   - adresare ze subdir_keep_list se zalohuji cele, i soubory .bin, .o, ...
#     (seznam je prazdny - vzory testu tests/examples/expected jsou jen .txt)

import sys, os, re, time, datetime, optparse

opt = None

GENERATED_MARKS = (
   "# Makefile is generated by cmini-makefiles.py",
   "# Makefile is generated by cecko-makefiles.py",   # Makefile z drivu nazvu skriptu
   "# Makefile is generated by makefiles.py",
   )

# --------------------------------------------------------------------------

# toplevel subdirectories ignored by no_orig option
toplevel_orig_list = ( "orig", )

# subdirectories with all files (test patterns)
subdir_keep_list = ( )

# local subdirectories for cleaning
subdir_clean_list = (
   ".git",
   ".deps",
   ".libs",
   "CMakeFiles",
   "__pycache__",

   "_build",     # objekty (cmini-makefiles.py)
   "_doxygen",
   "_input",
   "_import",
   "_library",   # asmjit (ASMJIT=local tests/build-test.sh)
   "_local",
   "_product",
   "_work",
   "_output",    # vystupy pro studenty (tests/vystup.sh); vystupy testu jsou v _build
   )

subdir_clean_patterns = (
   "build-.*-Debug",
   "build-.*-Release",
   )

# file names for cleaning
file_clean_list = (
   "CMakeCache.txt",
   "cmake_install.cmake",
   "a.out",
   )

# long file names for cleaning (relative to project directory)
file_remove_list = (
   )

# file extensions for cleaning
ext_clean_list = (
   ".pyc",
   ".moc",
   ".uic",
   ".o",
   ".dwo",
   ".lo",
   ".la",
   ".a",
   ".so",
   ".bin",        # cmini/test_instr.bin, cmini/cmini.bin -C, asm/pasm.bin

   ".gch",
   ".pch",
   ".pcs",
   ".kdevelop.pcs",
   ".kate-swp",
   )

# file name endings for cleaning
suffix_clean_list = (
   ".bin.asm",    # text pro assembler (test_instr.bin -o x.bin)
   ".bin.lst",
   )

# backup files for cleaning
file_backup_mark = "~"

# --------------------------------------------------------------------------

def generated_makefile (abs_file_name) :
    try :
       f = open (abs_file_name, "r")
       first = f.readline ().rstrip ("\n")
       f.close ()
    except (IOError, UnicodeDecodeError) :
       return False
    return first in GENERATED_MARKS

def remove_file (abs_dir, rel_dir, local_name, keep_all, autoclean_flag, autoclean_ext) :
    # True = vygenerovany soubor (uklid, nezalohuje se)

    if keep_all :
       return False

    abs_file_name = os.path.join (abs_dir, local_name)
    rel_file_name = os.path.join (rel_dir, local_name)

    if autoclean_flag :
       return True

    if local_name in file_clean_list :
       return True

    if rel_file_name in file_remove_list :
       return True

    if local_name == "Makefile" and generated_makefile (abs_file_name) :
       return True

    base, ext = os.path.splitext (local_name)
    if ext in ext_clean_list or ext in autoclean_ext :
       return True
    for suffix in suffix_clean_list :
        if local_name.endswith (suffix) :
           return True
    if local_name.endswith (file_backup_mark) :
       return True

    return False

def skip_subdir (local_name, rel_name, level, keep_all) :
    # (skip, remove): skip = neprochazet, remove = smazat pri uklidu

    if level == 1 and opt.no_orig and local_name in toplevel_orig_list :
       return True, False

    if keep_all :
       return False, False

    if local_name in subdir_clean_list :
       return True, True
    for pattern in subdir_clean_patterns :
        if re.match ("^" + pattern + "$", local_name) :
           return True, True

    return False, False

# --------------------------------------------------------------------------

def read_autoclean (abs_dir) :
    autoclean_files = [ ]
    autoclean_dirs = [ ]
    autoclean_ext = [ ]

    file_name = os.path.join (abs_dir, "autoclean")
    if not os.path.isfile (file_name) :
       file_name = os.path.join (abs_dir, "clean.sh")

    if os.path.isfile (file_name) :
       f = open (file_name, "r")
       for line in f :
          m = re.match (r"^\s*rm\s\s*(-f\s\s*)?(\S\S*)\s*$", line)
          if m :
              name = m.group (2)
              if not ('*' in name) :
                 autoclean_files.append (name)
          m = re.match (r"^\s*rmdir\s\s*(\S\S*)\s*$", line)
          if m :
              name = m.group (1)
              if not ('*' in name) :
                 autoclean_dirs.append (name)
          m = re.match (r"^\s*rm\s\s*-rf\s\s*(\S\S*)\s*$", line)
          if m :
              name = m.group (1)
              if not ('*' in name) :
                 autoclean_dirs.append (name)
          m = re.match (r"^\s*rm\s\s*\*\.(\S\S*)\s*$", line)
          if m :
              autoclean_ext.append ("." + m.group (1))
       f.close ()

    return autoclean_files, autoclean_dirs, autoclean_ext

# --------------------------------------------------------------------------

def scan_directory (abs_dir, rel_dir, out_dir, level, keep_all) :

    autoclean_files, autoclean_dirs, autoclean_ext = read_autoclean (abs_dir)

    subitems = os.listdir (abs_dir)
    subitems.sort ()

    subdirs = { }

    # subdirectories
    for local_name in subitems :
        abs_name = os.path.join (abs_dir, local_name)
        rel_name = os.path.join (rel_dir, local_name)
        out_name = os.path.join (out_dir, local_name)
        if os.path.isdir (abs_name) :
           subdirs [local_name] = True
           skip, remove = skip_subdir (local_name, rel_name, level, keep_all)
           if not keep_all and local_name in autoclean_dirs :
              skip, remove = True, True
           if opt.clean_files :
              if remove :
                 print ("rm -rf", rel_name)
           if not skip :
              sub_keep = keep_all or local_name in subdir_keep_list
              scan_directory (abs_name, rel_name, out_name, level + 1, sub_keep)

    # files
    for local_name in subitems :
        if local_name not in subdirs :
           autoclean_flag = local_name in autoclean_files
           remove = remove_file (abs_dir, rel_dir, local_name, keep_all, autoclean_flag, autoclean_ext)
           if opt.clean_files :
              if remove :
                 print ("rm", os.path.join (rel_dir, local_name))
           elif not remove :
              print_file (abs_dir, out_dir, local_name)

def print_file (abs_dir, out_dir, local_name) :
    if opt.use_time_limit :
       mtime = os.stat (os.path.join (abs_dir, local_name)).st_mtime
       if mtime <= opt.time_limit :
          return
    print (os.path.join (out_dir, local_name))

# --------------------------------------------------------------------------

def read_options () :

    parser = optparse.OptionParser ()

    parser.add_option ("-c", "--clean", dest="clean_files", action="store_true", help="generate script for cleaning")

    parser.add_option ("-t", "--today", dest="today", action="store_true")
    parser.add_option ("-p", "--prev",  dest="previous_days", action="store")
    parser.add_option ("-f", "--from",  dest="from_date", action="store")

    parser.add_option ("--one-dir-name", dest="one_dir_name", action="store_true", help="print names relative to parent directory")
    parser.add_option ("--no-orig",      dest="no_orig",      action="store_true", help="skip orig subdirectory")

    global opt
    (opt, arg) = parser.parse_args ()

    if len (arg) != 0 :
       parser.error ("too many arguments")

    if opt.from_date :
       if not re.match ("^\\d{4}-\\d{1,2}-\\d{1,2}$", opt.from_date) :
          parser.error ("bad date")

    if opt.previous_days :
       if not re.match ("^\\d{1,4}$", opt.previous_days) :
          parser.error ("bad date")

# --------------------------------------------------------------------------

def set_time_limit () :
   opt.use_time_limit = False
   opt.time_limit = None

   if opt.today :
      d = datetime.date.today ()
      opt.time_limit = time.mktime (d.timetuple ())
      opt.use_time_limit = True

   if opt.previous_days :
      d = datetime.date.today ()
      opt.time_limit = time.mktime (d.timetuple ())
      n = int (opt.previous_days)
      if n > 0 :
         n = n - 1 # --prev 0 and --prev 1 is equal to --today
      opt.time_limit = opt.time_limit - 86400 * n
      opt.use_time_limit = True

   if opt.from_date :
      d = datetime.datetime.strptime (opt.from_date, "%Y-%m-%d")
      opt.time_limit = time.mktime (d.timetuple ())
      opt.use_time_limit = True

# --------------------------------------------------------------------------

def run () :
    read_options ()
    set_time_limit ()

    abs_dir = os.path.abspath (os.path.dirname (sys.argv[0]))

    out_dir = ""
    if opt.one_dir_name :
       out_dir = os.path.basename (abs_dir)

    scan_directory (abs_dir, "", out_dir, 1, False)

# --------------------------------------------------------------------------

if __name__ == '__main__' :
   run ()

# --------------------------------------------------------------------------
